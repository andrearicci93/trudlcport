#!/usr/bin/env python3
"""Extract every shader of the installed DLC port (game folder mods/*.drm) into ./shaders for native_test.ps1.
Nothing in the game folder is written. Standard library only.
Usage: python native_extract.py --game "C:/Program Files (x86)/Steam/steamapps/common/Tomb Raider Underworld"
Output names: new_ps_<lib>_<slot>_<md5>.bin = shaders generated by the port (libs 2173, 2720-2783),
              pc_ps_/pc_vs_<lib>_<slot>_<md5>.bin = shaders that the port copies from the PC game."""
import argparse, hashlib, os, struct, sys, zlib

NEW_LIBS = {2173} | set(range(2720, 2784))

def cdrm_decode(d):
    if d[:4] not in (b'CDRM', b'MRDC'): return d
    n, = struct.unpack('<I', d[8:12])
    ents = [struct.unpack('<II', d[16 + 8 * i:24 + 8 * i]) for i in range(n)]
    pos = (16 + 8 * n + 15) & ~15
    out = bytearray()
    for u, c in ents:
        blk = d[pos:pos + c]
        out += zlib.decompress(blk) if (u & 0xff) == 2 else blk
        pos = (pos + c + 15) & ~15
    return bytes(out)

def shader_sections(raw):
    ver, namesz, padsz, u0, u1, n = struct.unpack('<iiiiii', raw[:24])
    secs, p = [], 24
    for _ in range(n):
        size, typ, pad, vid, packed, sid, spec = struct.unpack('<iBBHIII', raw[p:p + 20]); p += 20
        secs.append((size, typ, packed >> 8, sid))
    p += namesz + padsz
    for size, typ, nreloc, sid in secs:
        p += nreloc
        if typ == 9: yield sid, raw[p:p + size]
        p += size

def lib_blobs(d):
    """ShaderLib section: u8 kind, 3 pad, u32 tableBytes, u32 dataSize, u32 slot[]; entry @4+off: u32 junk, u32 size, u64 hash, bytecode."""
    tb, = struct.unpack_from('<I', d, 4)
    for slot, off in enumerate(struct.unpack_from('<%dI' % (tb // 4), d, 12)):
        if off == 0xffffffff: continue
        size, = struct.unpack_from('<I', d, 4 + off + 4)
        code = d[4 + off + 16:4 + off + 8 + size]
        for i in range(0, len(code) - 3, 4):   # cut at the END token
            if code[i:i + 4] == b'\xff\xff\x00\x00': code = code[:i + 4]; break
        yield slot, code

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--game', required=True)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'shaders'))
    a = ap.parse_args()
    mods = os.path.join(a.game, 'mods')
    if not os.path.isdir(mods): sys.exit('mods folder not found: ' + mods)
    os.makedirs(a.out, exist_ok=True)
    seen, ndrm, nnew = set(), 0, 0
    for dp, dn, fn in os.walk(mods):
        for f in sorted(fn):
            if not f.lower().endswith('.drm'): continue
            ndrm += 1
            raw = cdrm_decode(open(os.path.join(dp, f), 'rb').read())
            for sid, data in shader_sections(raw):
                for slot, code in lib_blobs(data):
                    md = hashlib.md5(code).hexdigest()
                    if md in seen: continue
                    seen.add(md)
                    kind = 'vs' if code[2:4] == b'\xfe\xff' else 'ps'
                    pre = 'new_' if sid in NEW_LIBS else 'pc_'
                    nnew += pre == 'new_'
                    open(os.path.join(a.out, '%s%s_%d_%d_%s.bin' % (pre, kind, sid, slot, md[:8])), 'wb').write(code)
    print('DRM: %d  shader unici: %d  generati dal port: %d  -> %s' % (ndrm, len(seen), nnew, a.out))

if __name__ == '__main__':
    main()
